def pick(key: str, options: list):
    """always the same choice for the same key (the same concept → the same words, visit after visit)."""
    return options[int(hashlib.md5(key.encode("utf-8")).hexdigest(), 16) % len(options)]


def say(key: str, seed: str, fem: bool = False, **kw) -> str:
    """the form of this line for this concept (seed = lesson + concept), names filled in, the verb agreeing with «me»."""
    t = pick(f"{key}:{seed}", POOL[key])
    t = re.sub(r"\[([^|\]]*)\|([^\]]*)\]", lambda m: m.group(2) if fem else m.group(1), t)
    return t.format(**kw)
